import { readdir,readFile,writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const files=['index.html','manifest.webmanifest'];
for(const dir of ['js','css','assets']){
  const paths=await readdir(path.join(root,dir),{recursive:true,withFileTypes:true});
  for(const item of paths)if(item.isFile())files.push(path.relative(root,path.join(item.parentPath,item.name)).replaceAll('\\','/'));
}
files.sort();
const hash=createHash('sha256');
for(const file of [...files,'sw.js'])hash.update(file).update(await readFile(path.join(root,file)));
const build=hash.digest('hex').slice(0,16);
await writeFile(path.join(root,'sw-assets.js'),'// Generated by node scripts/update-assets.mjs.\nself.BUILD_ID='+JSON.stringify(build)+';\nself.PRECACHE='+JSON.stringify(files.map(file=>'./'+file),null,2)+';\n');
console.log('Offline assets: '+files.length+'; build '+build);
